  venus: { pt: 'Vénus', en: 'Venus' },
  mars: { pt: 'Marte', en: 'Mars' },
  jupiter: { pt: 'Júpiter', en: 'Jupiter' },
  saturn: { pt: 'Saturno', en: 'Saturn' },
  uranus: { pt: 'Úrano', en: 'Uranus' },
  neptune: { pt: 'Neptuno', en: 'Neptune' },
  titan: { pt: 'Titã', en: 'Titan' },
